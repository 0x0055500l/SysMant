test('conflicto de cierre conserva datos y permite recuperar el listado', async ({ page }) => {
  const mock = await mockMaintenance(page); await login(page); await page.goto('/mantenimientos');
  await page.getByRole('button', { name: 'Cerrar orden', exact: true }).first().click();
  const close = page.getByRole('dialog', { name: 'Cerrar orden', exact: true });
  await close.getByLabel('Costo final (L) *', { exact: true }).fill('50.25'); mock.state.closeConflict = true;
  await close.getByRole('button', { name: 'Completar orden' }).click();
  await expect(close.getByRole('alert')).toContainText('ya fue completada');
  await expect(close.getByLabel('Costo final (L) *', { exact: true })).toHaveValue('50.25');
  await close.getByRole('button', { name: 'Actualizar listado y cerrar' }).click();
  await expect(close).not.toBeVisible(); await expect(page.locator('tbody tr')).toHaveCount(20);
  expect(mock.state.writes).toHaveLength(1);
});

test('fallback de técnico sin historial, responsable inválido y equipo no operativo', async ({ page }) => {
  const mock = await mockMaintenance(page); mock.state.knownEmpty = true;
  await login(page); await page.goto('/mantenimientos');
  await page.getByRole('button', { name: 'Programar mantenimiento', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Programar mantenimiento', exact: true });
  await expect(dialog.getByLabel('Ingresar ID de técnico')).toBeChecked();
  await dialog.getByLabel('Técnico responsable *', { exact: true }).fill(mock.ownId);
  await dialog.getByLabel('Equipo operativo *', { exact: true }).selectOption(mock.records[0].id);
  await dialog.getByLabel('Descripción / actividades *', { exact: true }).fill('Revisar motor');
  mock.records[0].estado = 'en_mantenimiento';
  await dialog.getByRole('button', { name: 'Guardar programación' }).click();
  await expect(dialog.getByRole('alert')).toContainText('ya no está operativo'); expect(mock.state.writes).toHaveLength(0);
  mock.records[0].estado = 'operativo'; mock.state.responsibleInvalid = true;
  await dialog.getByRole('button', { name: 'Guardar programación' }).click();
  await expect(dialog.getByRole('alert')).toContainText('técnico activo');
  await expect(dialog.getByLabel('Descripción / actividades *', { exact: true })).toHaveValue('Revisar motor');
});
