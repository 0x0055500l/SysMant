const { test, expect } = require('@playwright/test');
const { mockMaintenance, login } = require('./maintenance.fixture.cjs');

test('programación, inicio, cierre exacto y orden imprimible', async ({ page }, info) => {
  const mock = await mockMaintenance(page, 'supervisor'); await login(page);
  await page.goto('/mantenimientos');
  await page.getByRole('button', { name: 'Programar mantenimiento', exact: true }).click();
  const schedule = page.getByRole('dialog', { name: 'Programar mantenimiento', exact: true });
  await schedule.getByRole('button', { name: 'Guardar programación' }).click();
  expect(mock.state.writes).toHaveLength(0);
  await schedule.getByLabel('Equipo operativo *', { exact: true }).selectOption(mock.records[0].id);
  await schedule.getByLabel('Técnico responsable *', { exact: true }).selectOption(mock.ownId);
  await schedule.getByLabel('Fecha programada (UTC) *', { exact: true }).fill('2026-09-15T15:30');
  await schedule.getByLabel('Descripción / actividades *', { exact: true }).fill('Revisar filtros\nComprobar presión de servicio');
  await schedule.getByLabel('Costo estimado (L)', { exact: true }).fill('1250.50');
  await page.screenshot({ path: info.outputPath('programacion.png'), fullPage: true });
  await schedule.getByRole('button', { name: 'Guardar programación' }).click();
  await expect(schedule).not.toBeVisible();
  await expect(page.getByRole('status')).toContainText('programada');
  expect(mock.state.writes[0].body.costo).toBe('1250.50');
  expect(mock.state.writes[0].body.fecha_programada).toBe('2026-09-15T15:30:00Z');
  await page.getByLabel('Programada desde (UTC)', { exact: true }).fill('2026-09-15');
  await page.getByLabel('Hasta (UTC)', { exact: true }).fill('2026-09-15');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: 'Iniciar trabajo', exact: true }).click();
  const start = page.getByRole('dialog', { name: 'Iniciar trabajo', exact: true });
  await expect(start.getByRole('button', { name: 'Cancelar', exact: true })).toBeFocused();
  await page.keyboard.press('Escape'); await expect(start).not.toBeVisible(); expect(mock.state.writes).toHaveLength(1);
  await page.getByRole('button', { name: 'Iniciar trabajo', exact: true }).click();
  await start.getByRole('button', { name: 'Confirmar inicio' }).click();
  await expect(page.locator('tbody')).toContainText('En proceso');
  await page.getByRole('button', { name: 'Cerrar orden', exact: true }).click();
  const close = page.getByRole('dialog', { name: 'Cerrar orden', exact: true });
  await close.getByLabel('Costo final (L) *', { exact: true }).fill('1,200.00');
  await close.getByRole('button', { name: 'Completar orden' }).click();
  await expect(close).toContainText('sin comas ni símbolos'); expect(mock.state.writes).toHaveLength(2);
  await close.getByLabel('Costo final (L) *', { exact: true }).fill('9999999999.99');
  await close.getByLabel('Fecha de realización (UTC) *', { exact: true }).fill('9999-01-01T00:00');
  await close.getByRole('button', { name: 'Completar orden' }).click();
  await expect(close).toContainText('no futura'); expect(mock.state.writes).toHaveLength(2);
  await close.getByLabel('Fecha de realización (UTC) *', { exact: true }).fill('2026-09-12T10:00');
  await close.getByLabel('Observaciones finales', { exact: true }).fill('Sellos y presión verificados.');
  await page.screenshot({ path: info.outputPath('cierre.png'), fullPage: true });
  await close.getByRole('button', { name: 'Completar orden' }).click();
  await expect(close).not.toBeVisible(); await expect(page.locator('tbody')).toContainText('Completado');
  await expect(page.getByRole('button', { name: 'Cerrar orden', exact: true })).toHaveCount(0);
  expect(mock.state.writes[2].body).toEqual({ fecha_realizada: '2026-09-12T10:00:00Z', costo: '9999999999.99', observaciones: 'Sellos y presión verificados.' });
  await page.getByRole('button', { name: 'Ver / imprimir', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Vista previa de la orden' })).toBeFocused();
  await expect(page.getByRole('article')).toContainText('Inversiones de la Costa');
  await expect(page.getByRole('article')).toContainText('9,999,999,999.99');
  await page.evaluate(() => { window.print = () => { window.__printed = true; }; });
  await page.getByRole('button', { name: 'Imprimir orden / Guardar PDF' }).click();
  expect(await page.evaluate(() => window.__printed)).toBe(true);
  await page.emulateMedia({ media: 'print' });
  await expect(page.locator('app-navbar')).not.toBeVisible();
  await expect(page.getByRole('article')).toBeVisible();
  await expect(page.locator('.print-controls')).not.toBeVisible();
  await page.screenshot({ path: info.outputPath('orden-print.png'), fullPage: true });
  if (info.project.name === 'desktop') await page.pdf({ path: info.outputPath('orden-trabajo.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true });
  await page.emulateMedia({ media: 'screen' });
  await page.getByRole('button', { name: 'Volver al listado' }).click();
  await expect(page.getByRole('button', { name: 'Ver / imprimir', exact: true })).toBeFocused();
});

